/**
 * Finds the closest BMKG weather station to any given coordinates [lat, lng].
 */
export function findNearestBmkgStation(coords: [number, number]): BmkgWeatherStation {
  let minDistance = Infinity;
  let nearest = BMKG_STATIONS[0];

  const [lat, lng] = coords;
  for (const station of BMKG_STATIONS) {
    const dLat = station.coordinates[0] - lat;
    const dLng = station.coordinates[1] - lng;
    const distSq = dLat * dLat + dLng * dLng;
    if (distSq < minDistance) {
      minDistance = distSq;
      nearest = station;
    }
  }

  return nearest;
}
